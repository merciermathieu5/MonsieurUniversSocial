/*
 * Test de la carte de la zone agricole (fiche de géographie 10) dans un DOM simulé.
 *     node outils/test_zone_agricole_qc.js [composant.html]
 */
const fs = require("fs");
const path = require("path");
const { JSDOM } = require("jsdom");
const RACINE = path.join(__dirname, "..");
const fichier = process.argv[2] || path.join(RACINE, "theme", "composants", "zone-agricole-qc.html");
const composant = fs.readFileSync(fichier, "utf8");
const dom = new JSDOM(`<!DOCTYPE html><html lang="fr-CA"><head><meta charset="utf-8"></head><body><main><article class="fiche"><div class="texte">${composant}</div></article></main></body></html>`, { runScripts: "outside-only", pretendToBeVisual: true });
const { window } = dom;
window.scrollTo = () => {};
const script = composant.slice(composant.indexOf("<script>") + 8, composant.lastIndexOf("</script>"));
window.eval(script);
const pageJs = path.join(RACINE, "theme", "page.js");
if (fs.existsSync(pageJs)) window.eval(fs.readFileSync(pageJs, "utf8"));
window.eval(script);
const racine = window.document.getElementById("zone-agricole-qc");
let echecs = 0;
function verifier(nom, ok, detail) { console.log(`    ${ok ? "ok     " : "ECHEC  "}${nom}${!ok && detail !== undefined ? "  (" + detail + ")" : ""}`); if (!ok) echecs++; }
const un = (s) => racine.querySelector(s), tous = (s) => Array.from(racine.querySelectorAll(s));
const clic = (el) => el && el.dispatchEvent(new window.MouseEvent("click", { bubbles: true }));
const touche = (k) => racine.dispatchEvent(new window.KeyboardEvent("keydown", { key: k, bubbles: true }));
const choix = () => racine.getAttribute("data-choix");
const api = racine.zaq;
const textes = [];
const lire = () => textes.push(un(".zaq__lecture").textContent);
console.log("MISE EN PLACE");
verifier("composant présent et initialisé une seule fois", !!racine && racine.getAttribute("data-pret") === "1" && racine.classList.contains("est-pret"));
verifier("page.js ajoute Réinitialiser avant Plein écran", !!un(".zaq__entete .reinitialiser") && un(".zaq__entete .reinitialiser").nextElementSibling === un(".zaq__entete .plein-ecran"));
verifier("au départ : aucun choix", choix() === "");
lire();
const depart = JSON.stringify(api.etat());

console.log("DONNÉES");
verifier("100 MRC et territoires dessinés", tous(".zaq__mrc").length === 100, tous(".zaq__mrc").length);
verifier("17 régions", api.reg().length === 17);
verifier("Montréal : 2 046 ha, 4 %", api.mrc().some((m) => m.id === "montreal" && m.za === 2046 && m.pct === 4));
verifier("Lotbinière : 98 %, classe la plus foncée", un('.zaq__mrc[data-mrc="lotbiniere"]').getAttribute("data-classe") === "5");
verifier("fiche d'accueil : 6 311 048 ha, 4,7 %", /6 311 048/.test(un(".zaq__vue").textContent) && /4,7/.test(un(".zaq__vue").textContent));
console.log("CHOIX ET DÉSÉLECTION");
clic(un('.zaq__mrc[data-mrc="laval"]'));
verifier("un clic sur Laval ouvre sa fiche", choix() === "mrc:laval" && /29 %/.test(un(".zaq__vue").textContent)); lire();
verifier("Laval est entourée", un(".zaq__choix").getAttribute("d") === un('.zaq__mrc[data-mrc="laval"]').getAttribute("d"));
clic(un('.zaq__mrc[data-mrc="laval"]'));
verifier("un second clic désélectionne", choix() === "" && un(".zaq__choix").getAttribute("d") === "");
clic(tous(".zaq__vue .zaq__choisir").find((b) => /Grand Montréal/.test(b.textContent)));
verifier("le Grand Montréal : 58 %, contour affiché", choix() === "cmm:cmm" && /58 %/.test(un(".zaq__vue").textContent) && racine.classList.contains("avec-cmm")); lire();
verifier("depuis une liste, la carte se rapproche", un(".zaq__svg").getAttribute("viewBox") !== "0 0 1000 464");
touche("Escape");
verifier("Échap désélectionne", choix() === "");
api.choisir({ type: "reg", id: "16" }); lire();
verifier("fiche de la Montérégie : MRC listées, autres régions estompées", /Montérégie/.test(un(".zaq__vue").textContent) && tous(".zaq__mrc.est-estompe").length === 100 - 13);
api.choisir({ type: "reg", id: "10" }); lire();
verifier("Nord-du-Québec : la Jamésie hors carte est listée", /Jamésie/.test(un(".zaq__vue").textContent));
api.choisir(null);
console.log("COUCHES");
clic(un('.zaq__couche[data-mode="ha"]'));
verifier("mode hectares : cercles affichés", racine.classList.contains("mode-ha") && tous(".zaq__cercle").length >= 95);
clic(un('.zaq__couche[data-couche="regions"]'));
verifier("masquer les régions", !racine.classList.contains("avec-regions"));
clic(un(".zaq__zoom-plus"));
verifier("le bouton + rapproche la carte", !un(".zaq__recentrer").hidden);
api.mrc().forEach((m) => { api.choisir({ type: "mrc", id: m.id }); lire(); }); api.choisir(null);

console.log("RÉINITIALISATION");
clic(un(".zaq__replier"));
clic(un(".zaq__entete .reinitialiser"));
verifier("Réinitialiser ramène l'état exact du départ", JSON.stringify(api.etat()) === depart, JSON.stringify(api.etat()));
verifier("Réinitialiser garde le texte masqué", racine.classList.contains("texte-masque"));
const carte = un(".zaq__carte");
const doigt = (x, y, id) => ({ clientX: x, clientY: y, identifier: id, target: carte });
const toucher = (type, liste) => { const ev = new window.Event(type, { bubbles: true, cancelable: true }); ev.touches = liste; carte.dispatchEvent(ev); return ev; };
const avant = un(".zaq__svg").getAttribute("viewBox"), raf = window.requestAnimationFrame;
window.requestAnimationFrame = undefined;
const d1 = toucher("touchstart", [doigt(300, 300, 1), doigt(340, 300, 2)]);
toucher("touchmove", [doigt(260, 300, 1), doigt(380, 300, 2)]);
toucher("touchend", []);
window.requestAnimationFrame = raf;
verifier("pincer à deux doigts rapproche la carte", d1.defaultPrevented && un(".zaq__svg").getAttribute("viewBox") !== avant && carte.classList.contains("est-zoomee"));
clic(un(".zaq__entete .reinitialiser"));
verifier("Réinitialiser ramène la carte entière", un(".zaq__svg").getAttribute("viewBox") === avant && un(".zaq__recentrer").hidden);
console.log("TYPOGRAPHIE ET STRUCTURE");
lire();
const copie = racine.cloneNode(true); copie.querySelectorAll("style, script, svg").forEach((n) => n.remove());
const t = copie.textContent + textes.join(" ") + Array.from(racine.querySelectorAll("svg text")).map((n) => n.textContent).join(" ");
verifier("aucun tiret cadratin ou demi-cadratin", !/[–—]/.test(t));
verifier("aucune virgule devant « et »", !/, et /.test(t));
verifier("aucune espace avant ; ! ?", !/[   ][;!?]/.test(t));
verifier("espace insécable devant les deux-points", !/ :/.test(t));
const ids = tous("[id]").map((n) => n.id).concat([racine.id]);
verifier("aucun id en double", new Set(ids).size === ids.length);
verifier("classes préfixées zaq__", tous("[class]").every((n) => { const c = n.getAttribute("class"); return !c || /(^|\s)zaq/.test(c) || /reinitialiser|plein-ecran|entete-actions/.test(c); }));
verifier("sources citées", /CPTAQ/.test(un(".zaq__source").textContent));
console.log(echecs ? `\n${echecs} échec(s).` : "\nTout est conforme.");
process.exit(echecs ? 1 : 0);
